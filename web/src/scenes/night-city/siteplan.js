// 지상 배치 계획 — 무엇이 어디를 차지하는지에 대한 단일 출처.
//
// ── 왜 필요한가 ────────────────────────────────────────────────────────────
// 지상에 물건을 놓는 모듈이 다섯이다.
//
//   streets.js      가로등 · 신호등
//   sidewalk.js     점자블록 · 맨홀 · 배수구
//   streetlife.js   자판기 · 쉘터 · 포장마차 · 배전함 · 화분
//   vertical.js     2층 데크 기둥 · 계단
//   alley.js        골목 입구 · 볼라드
//
// 다섯이 전부 **자기 난수와 자기 간격 규칙으로 독립적으로** 놓고 있었다.
// 서로의 존재를 모르니 당연히 겹친다. 실제로 이렇게 됐다.
//
//   · 가로등 기둥이 골목 입구 한가운데 박혔다
//   · 계단이 점자블록 위로 내려앉았다
//   · 볼라드가 입구가 아니라 골목 안쪽에 섰다
//   · 자판기가 계단 착지점을 막았다
//
// 이건 값을 조정해서 고칠 문제가 아니다. **놓는 순서와 우선순위가 없다**는
// 구조의 문제다.
//
// ── 우선순위 (실제 도시계획의 순서와 같다) ─────────────────────────────────
// 아래로 갈수록 양보한다. 위의 것이 이미 차지한 자리에는 놓지 않는다.
//
//   1 고정 인프라   도로 · 교차로 · 횡단보도       움직일 수 없다
//   2 진입 동선     골목 입구 · 건물 출입구        막으면 통로가 죽는다
//   3 수직 동선     계단 착지점 · 데크 기둥        구조물이라 못 비킨다
//   4 안전·안내     점자블록 · 볼라드 · 신호등     법으로 위치가 정해진다
//   5 조명          가로등                         일정 간격이되 위를 피한다
//   6 편의 시설     자판기 · 쉘터 · 화분 · 배전함  남은 자리를 채운다
//
// ── 왜 원(circle)으로 다루는가 ─────────────────────────────────────────────
// 사각형 교차 판정이 더 정확하지만, 여기서 필요한 것은 "사람이 지나갈 틈이
// 있는가" 이지 밀리미터 단위 접촉이 아니다. 원은 회전을 신경 쓸 필요가 없고
// 판정이 거리 비교 한 번이다. 실제로 인도 위 물건은 대부분 뭉툭하다.
export const TIER = {
  INFRA: 1,
  ACCESS: 2,
  VERTICAL: 3,
  SAFETY: 4,
  LIGHT: 5,
  AMENITY: 6,
  // 바닥에 그리는 것(점검구·표시). 가장 낮다 — 위의 무엇이든 있으면 양보한다.
  // 평평해서 충돌해도 덜 티가 나지만, 계단 밑이나 자판기 밑에 점검구가
  // 깔려 있으면 "아무 데나 뿌렸다" 는 인상이 그대로 남는다.
  GROUND: 7,
};

// 차지한 자리 목록. 씬 빌드마다 초기화한다.
let claims = [];

export function resetPlan() {
  claims = [];
}

// (x, z) 를 중심으로 반지름 r 을 차지하겠다고 등록한다.
// 이미 **더 높은 우선순위**가 겹쳐 있으면 false 를 돌려주고 등록하지 않는다.
//
// 같은 등급끼리도 겹치면 거절한다 — 자판기 두 대가 같은 자리에 서면 안 된다.
export function claim(x, z, r, tier, label = '') {
  for (const c of claims) {
    const d = Math.hypot(c.x - x, c.z - z);
    if (d >= c.r + r) continue;
    // 내가 더 높은 우선순위(작은 숫자)면 밀어내지 않고 그냥 함께 둔다 —
    // 예: 볼라드는 골목 입구 '안'에 서는 것이 정상이다.
    if (tier < c.tier) continue;
    return false;
  }
  claims.push({ x, z, r, tier, label });
  return true;
}

// 등록하지 않고 물어보기만 한다. 배치 전에 자리를 고를 때 쓴다.
export function isFree(x, z, r, tier) {
  for (const c of claims) {
    if (Math.hypot(c.x - x, c.z - z) >= c.r + r) continue;
    if (tier < c.tier) continue;
    return false;
  }
  return true;
}

// 진단용. 어느 등급이 몇 자리를 차지했는지.
export function planStats() {
  const by = {};
  for (const c of claims) by[c.label || c.tier] = (by[c.label || c.tier] || 0) + 1;
  return by;
}
