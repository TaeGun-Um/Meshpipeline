// 야간 도시의 대기와 광원.
//
// ── 광원 예산 ──────────────────────────────────────────────────────────────
// 창문이 수만 개인 도시를 점광원으로 만들 방법은 없고, 엔진 포워드 렌더링은
// 오브젝트당 픽셀 광원이 4개다. 게다가 지오메트리를 큰 메시 몇 개로 병합했으므로
// "오브젝트당 4개" 가 사실상 "씬 전체에 4개" 가 된다.
//
// 그래서 이 씬의 빛은 세 갈래뿐이다.
//   1) 발광 표면 (창문·간판·광고판)     — 물체 자신이 보이게
//   2) 씬 전체로 구운 환경맵            — 그 발광이 다른 표면을 물들이게
//   3) 빛 웅덩이 (가산합성 지오메트리)  — 발광이 바닥·벽을 밝히는 것처럼
// 실제 광원은 방향광 1(달) + 반구광 1, 끝이다.
import * as THREE from 'three';
import { createSkyDome } from '../../shared/sky.js';
import { SKY_STOPS, FOG_COLOR, FOG_DENSITY } from './palette.js';
import { CITY_HALF } from './layout.js';

export function createSky(scene) {
  // 원경 스카이라인(최대 2.4km)보다 커야 한다
  return createSkyDome(scene, SKY_STOPS, { radius: 3600, segments: 40, rings: 24 });
}

export function createLights(scene) {
  scene.fog = new THREE.FogExp2(FOG_COLOR, FOG_DENSITY);

  // ── 밝기 위계가 뒤집혀 있었다 (실측으로 고침) ───────────────────────────
  //
  // 사용자 지적: "위를 향한 면이 도시에서 제일 밝다."
  // `tools/lumi.mjs` 로 재 보니 그대로였다.
  //
  //   내려다본 화면(수평면)  평균 24.9 · 중앙 20.7
  //   거리 시선(수직면)      평균 10.7 · 중앙  4.1
  //
  // **평균 2.3배, 중앙값 5배.** 밤 도시에서 노면이 벽보다 밝을 이유가 없다.
  // 레퍼런스의 노면은 젖은 아스팔트라 어둡고, 밝은 것은 간판·창·조명뿐이다.
  //
  // 원인은 광원 셋이 **전부 수평면 편향**이라는 것이었다.
  //   1) 반구광    normal.y 로 보간하므로 위를 향한 면에 하늘색 100%
  //   2) 달        y=400 에 고도 51도 — 지붕과 노면에 거의 수직 입사
  //   3) 환경맵    상반구가 하늘이라 위를 향한 면이 더 받는다
  //
  // ── 세기를 내리는 것만으로는 안 됐다 ───────────────────────────────────
  // 1.15 -> 0.42 로 내렸더니 노면은 잡혔는데 **파사드가 통째로 검어졌다**
  // (거리 시선 중앙값 4.1 -> 1.3). 반구광은 위 1.0 / 옆 0.5 / 아래 0.0 으로
  // 보간하므로, 세기만 건드리면 셋이 같은 비율로 어두워질 뿐이다.
  // 위와 옆을 **갈라 놓을 수가 없다.**
  //
  // 갈라 놓는 곳은 세기가 아니라 **위아래 색**이다.
  //
  //   하늘색  위를 향한 면       -> 어둡게. 밤하늘은 어둡다
  //   땅색    아래를 향한 면     -> 밝게.  젖은 노면이 네온을 위로 튕긴다
  //   옆면    둘의 중간을 받는다 -> 자동으로 노면보다 밝아진다
  //
  // 원래 주석이 이미 "아래는 자주 — 네온이 젖은 노면에 반사" 라고 적고
  // 있었다. **의도는 맞았고 값이 반대였다** — 하늘색(0x4a6ea8)이 땅색보다
  // 훨씬 밝았다. 이 도시에서 그 둘의 크기 관계는 뒤집혀야 한다.
  const hemi = new THREE.HemisphereLight(0x1c2a44, 0x7a4480, 0.95);
  hemi.name = 'Ambient';
  scene.add(hemi);

  // 달빛. 도시에서 유일한 그림자원.
  // 그림자 카메라가 도시 전체를 덮어야 하므로 범위가 크고, 그만큼 해상도당
  // 실효 정밀도가 떨어진다. 4096 을 써도 픽셀당 13cm 수준이다.
  //
  // **눕혔다.** 고도 51도 -> 20도. 높은 달은 지붕과 노면을 때리는데,
  // 낮은 달은 벽을 스치듯 훑어서 파사드의 요철을 드러낸다 — 같은 밝기로
  // 형태가 더 읽힌다.
  const moon = new THREE.DirectionalLight(0xa9c2f2, 0.72);
  moon.name = 'Moon';
  moon.position.set(-420, 190, 300);
  moon.castShadow = true;
  moon.shadow.mapSize.set(4096, 4096);
  const s = moon.shadow.camera;
  const r = CITY_HALF * 1.15;
  s.left = -r;
  s.right = r;
  s.top = r;
  s.bottom = -r;
  s.near = 1;
  s.far = 1200;
  moon.shadow.bias = -0.0012;
  moon.shadow.normalBias = 0.06;
  scene.add(moon);

  return { hemi, moon };
}
