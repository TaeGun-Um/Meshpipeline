// 대기. 안개색은 씬의 어두운 부분보다 밝아야 한다. 어둡게 두면 원경이 검은
// 공백이 되어 "안개에 잠겼다" 가 아니라 "아무것도 없다" 로 보인다.
export const FOG_COLOR = 0x1d1730;

// 지수 안개 밀도. 감쇠는 exp(-(거리·ρ)²) 이다.
//
// 이 값을 두 번 크게 틀렸다.
//   0.021  (골목 씬에서 가져온 값) → 50m 앞이 사라져 도시가 아예 안 보인다
//   0.0042 → 200m 에서 절반, 400m 에서 94%. 원경 스카이라인이 통짜 실루엣이
//            되고 화면 전체가 저채도 라벤더로 씻긴다
// 0.0014 면 400m 에서 30% 정도라 초고층 윗부분이 살아남고 2km 원경은 잠긴다.
// 도시에서 안개는 "가리는 것" 이 아니라 "층을 나누는 것" 이어야 한다.
export const FOG_DENSITY = 0.0014;
