//
// 이 매핑이면 그림의 부둣가(공장을 아래·오른쪽으로 감싸는 L)가 **실제 부두가
// 있는 -X 변**과 +Z 물가에 정확히 떨어진다. 좌우는 거울 대칭이라 자유도가
// 하나 남지만, 그건 도시를 뒤집는 것뿐이라 언제든 바꿀 수 있다.
//
// 행은 ix 11(위=육지)에서 0(아래=부두)으로 내려가고, 열은 iz 0에서 11이다.
// 즉 **아래 그림이 곧 사용자의 그림과 같은 방향**이다.
