const GLYPH = {
  '기': 'corpo', '상': 'market', '주': 'residential',
  '슬': 'slum', '공': 'industrial', '부': 'waterfront',
};

// ── 실측 결과 ──────────────────────────────────────────────────────────────
//
//   주거 26% · 상업 22% · 기업 21% · 부둣가 12.5% · 공업 10% · 슬럼 8%
//
// 옛 방식(씨앗 + 가중 보로노이)과 비교하면 끊긴 덩어리가 구역마다 **1개**로
// 보장된다 — 지도를 한 덩어리로 칠했기 때문이다. 보로노이는 씨앗이 여럿이면
// 반드시 여러 덩어리가 됐고, 그래서 슬럼이 도시 양쪽에 흩어져 있었다.

// ── 구역별 표는 완전해야 한다 ──────────────────────────────────────────────
//
// ── 왜 필요한가 (코드리뷰에서 실측) ──────────────────────────────────────
// 모듈 넷이 구역 이름을 열쇠로 쓰는 표를 각자 갖고 있었다.
//
//   crowd.DENSITY   상업·기업·주거·공업   `?? 0.2`
//   parking.DENSITY 상업·기업·주거·공업   `?? 0.5`
//   holo.RATE       상업·기업·주거·공업   `?? 0`
//   alley.WALL_H    상업·주거·공업·기업   `?? 20`
//
// 넷 다 **슬럼이 없다.** 슬럼을 만든 뒤로 계속 그랬다. 그리고 부둣가를
// 새로 만들자 같은 일이 한 번 더 일어났다 — 그 결과 실측으로:
//
//   · 부둣가의 사람 밀도가 0.2 로, **기업(0.14)보다 붐빈다.**
//     컨테이너 야드가 밤에 사옥 앞보다 사람이 많다는 뜻이다
//   · 부둣가 주차 밀도가 0.5 로, 주거(0.66) 다음으로 빽빽하다
//
// 아무도 그렇게 정한 적이 없다. **`??` 가 정했다.**
//
// 빠뜨린 것이 잘못이 아니라 **빠뜨릴 수 있는 구조가 잘못**이다. 구역이
// 하나 늘 때마다 표 넷을 찾아다니는 것은 사람이 할 일이 아니다.
// 그래서 표를 이 함수로만 만들게 하고, 하나라도 빠지면 **터뜨린다.**
export function byZone(label, table) {
  const want = Object.values(DISTRICTS).map((d) => d.name);
  const missing = want.filter((n) => !(n in table));
  if (missing.length) {
    throw new Error(
      `구역별 표 '${label}' 에 ${missing.join('·')} 이(가) 없다. ` +
      `구역을 추가했으면 이 표에도 값을 정해 줘야 한다 — ` +
      `기본값으로 얼버무리면 아무도 정하지 않은 숫자가 도시에 반영된다.`
    );
  }
  const extra = Object.keys(table).filter((n) => !want.includes(n));
  if (extra.length) throw new Error(`구역별 표 '${label}' 에 없는 구역 ${extra.join('·')} 이(가) 있다`);
  return table;
}

// 블록마다 한 번만 정하고 붙들어 둔다. 모듈 여덟이 각자 부르므로
// (crowd·parking·holo·streets·streetlife·vertical·towers·index) 매번
// 지도를 훑으면 낭비다.
let ZONE_CACHE = null;

function buildZones() {
  const out = new Array(GRID * GRID);
  for (let ix = 0; ix < GRID; ix++) {
    for (let iz = 0; iz < GRID; iz++) {
      // PLAN 의 행 0 이 ix 11 이다 (그림과 같은 방향으로 읽히게)
      const row = PLAN[GRID - 1 - ix];
      const kind = GLYPH[row[iz]];
      if (!kind) throw new Error(`PLAN(ix=${ix}, iz=${iz}) 글자 '${row[iz]}' 를 모른다`);
      out[iz * GRID + ix] = kind;
    }
  }
  return out;
}

// 블록 하나의 구역. 좌표만 보므로 언제 불러도 같은 답이 나온다 —
// 그래서 layout(필지 분할) 과 towers(외관) 가 각자 불러도 어긋나지 않는다.
//
// 예전에는 코어 거리를 인자로 받았는데, 배치가 씨앗으로 정해지면서 쓰이지
// 않게 됐다. 호출부 여덟 곳이 각자 coreDistance 를 계산해 넘기고 있었으므로
// (**같은 값을 여러 곳에서 계산**) 인자를 없앴다.
export function districtAt(ix, iz) {
  if (!ZONE_CACHE) ZONE_CACHE = buildZones();
  const cx = Math.max(0, Math.min(GRID - 1, ix));
  const cz = Math.max(0, Math.min(GRID - 1, iz));
  return DISTRICTS[ZONE_CACHE[cz * GRID + cx]];
}

// 구역별 블록 수. 비율을 실측으로 맞출 때 쓴다.
export function districtTally() {
  if (!ZONE_CACHE) ZONE_CACHE = buildZones();
  const t = {};
  for (const k of ZONE_CACHE) t[k] = (t[k] || 0) + 1;
  return t;
}

// 구역이 정한 가중치로 건물 유형을 고른다 (facade.pickArchetype 을 대체).
export function pickArchetypeIn(rng, district, height, width) {
  const w = { ...district.archetype };
  // 외골격은 넓고 높은 것에만 — 구역 가중치와 무관한 물리적 조건
  if (!(height > 110 && width > 20)) w.exo = 0;

  let total = 0;
  for (const k of Object.keys(w)) total += w[k];
  let acc = rng.next() * total;
  for (const k of Object.keys(w)) {
    acc -= w[k];
    if (acc <= 0) return k;
  }
  return 'grid';
}
